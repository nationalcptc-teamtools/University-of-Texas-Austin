import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import type { FieldData, ImagesData, TypstData, TypstInput } from "./data.ts";
import { PACKAGE_DIR } from "./package-dir.ts";

/** An image to ship, and the extension Typst should decode it by, if its format is known. */
export type ExportAsset = { bytes: Uint8Array; extension: string | undefined };

const TYP_DIR = join(PACKAGE_DIR, "typ");
const FONTS_DIR = join(PACKAGE_DIR, "fonts");

/** The report entry and what it imports; the finding and field entries cannot compile here. */
const TEMPLATES = ["components.typ", "data.typ", "finding.typ", "prose.typ", "report-main.typ"];
const DATA_FROM_JSON = '#let data = json("/data.json")';

const MAIN = `// Generated by burokrat for Typst 0.14.2; newer versions lay the report out slightly differently.
// The content is in report.typ. Compile with: typst compile main.typ --font-path fonts
#include "/typ/report-main.typ"
`;

const REPORT_HEADER = `// The report's content, generated by burokrat for Typst 0.14.2. Edit this file, then compile main.typ.
//
// - Text fields are Typst markup between \`\`\` fences. Write [REDACTED] rather than using # $ @,
//   which Typst reads as code, maths and references. If the text needs as many backticks in a row
//   as the fence has, lengthen both fences.
// - IPs and hostnames appear in \`hosts\`, in each finding's \`scope\` and in its text: search the
//   whole file. Images are in assets/, named by each \`images\` entry and the cover.
// - Removing a finding from \`findings\` also updates the counts in the report.
// - Fields with a Typst error are exported as they are, though the app would refuse the PDF.

#let prose(raw) = (source: raw.text, error: none)

`;

const INLINE_WIDTH = 100;

const isField = (value: object): value is FieldData => Object.keys(value).join() === "source,error";

/** Typst reads every character in the class but `\` and `"` as a line break or control. */
const NEEDS_ESCAPE = /[\\"\p{Cc}\u2028\u2029]/gu;

function typstString(text: string) {
  const escaped = text.replace(NEEDS_ESCAPE, (char) => {
    if (char === "\\" || char === '"') return `\\${char}`;
    if (char === "\n") return "\\n";
    return `\\u{${char.codePointAt(0)!.toString(16)}}`;
  });
  return `"${escaped}"`;
}

/** Markup as written, in a raw block whose fence is longer than any backtick run inside it. */
function proseBlock(source: string) {
  const longest = Math.max(0, ...(source.match(/`+/g) ?? []).map((run) => run.length));
  const fence = "`".repeat(Math.max(3, longest + 1));
  return `prose(${fence}\n${source}\n${fence})`;
}

/** On one line if it fits, else one item per line. A lone array item needs its trailing comma. */
function joined(items: string[], indent: string, isArray: boolean) {
  const inline = `(${items.join(", ")}${isArray && items.length === 1 ? "," : ""})`;
  if (inline.length + indent.length <= INLINE_WIDTH && !inline.includes("\n")) return inline;
  const inner = indent + "  ";
  return `(\n${items.map((item) => `${inner}${item},`).join("\n")}\n${indent})`;
}

/** A Typst literal for JSON-like data. Keys are always quoted, as image names may be keywords. */
export function typstValue(value: unknown, indent = ""): string {
  if (value === null || value === undefined) return "none";
  if (typeof value === "string") return typstString(value);
  if (typeof value === "number" || typeof value === "boolean") return String(value);
  if (Array.isArray(value)) {
    if (value.length === 0) return "()";
    return joined(
      value.map((item) => typstValue(item, indent + "  ")),
      indent,
      true,
    );
  }
  if (isField(value)) return proseBlock(value.source);
  const entries = Object.entries(value);
  if (entries.length === 0) return "(:)";
  return joined(
    entries.map(([key, item]) => `${typstString(key)}: ${typstValue(item, indent + "  ")}`),
    indent,
    false,
  );
}

/** The data with every asset id replaced by its file name in the export. */
function renameAssets(data: TypstData, fileOf: (id: string) => string): TypstData {
  const renamed = structuredClone(data);
  const renameImages = (images: ImagesData) => {
    for (const image of Object.values(images)) image.asset = fileOf(image.asset);
  };
  for (const finding of renamed.findings) renameImages(finding.images);
  if (renamed.report) {
    const { cover } = renamed.report;
    renameImages(renamed.report.images);
    if (cover.logo) cover.logo = fileOf(cover.logo);
    if (cover.background) cover.background = fileOf(cover.background);
  }
  return renamed;
}

function reportSource(data: TypstData) {
  const { company, team, report, hosts, findings, risk } = data;
  const ordered = { company, team, report, hosts, findings, risk };
  return `${REPORT_HEADER}#let data = ${typstValue(ordered)}\n`;
}

function dataTemplate() {
  const source = readFileSync(join(TYP_DIR, "data.typ"), "utf8");
  if (!source.includes(DATA_FROM_JSON))
    throw new Error(`typ/data.typ no longer has ${DATA_FROM_JSON}`);
  return source.replace(DATA_FROM_JSON, '#import "/report.typ": data');
}

/**
 * The report as a Typst project a reader can edit and compile: the templates, its content as one
 * `report.typ`, its images and the fonts. Throws if an image it shows has not been uploaded.
 */
export function exportReport(input: TypstInput, assets: Record<string, ExportAsset>) {
  const missing = input.assetIds.filter((id) => !assets[id]);
  if (missing.length > 0) {
    throw new Error(`${missing.length} image(s) in the report have not reached the server yet.`);
  }
  const fileOf = (id: string) => (assets[id]!.extension ? `${id}.${assets[id]!.extension}` : id);
  const encoder = new TextEncoder();
  const files: Record<string, Uint8Array> = {
    "main.typ": encoder.encode(MAIN),
    "report.typ": encoder.encode(reportSource(renameAssets(input.data, fileOf))),
  };
  for (const name of TEMPLATES) {
    files[`typ/${name}`] =
      name === "data.typ" ? encoder.encode(dataTemplate()) : readFileSync(join(TYP_DIR, name));
  }
  for (const name of readdirSync(FONTS_DIR))
    files[`fonts/${name}`] = readFileSync(join(FONTS_DIR, name));
  for (const id of input.assetIds) files[`assets/${fileOf(id)}`] = assets[id]!.bytes;
  return files;
}
